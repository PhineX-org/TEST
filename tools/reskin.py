#!/usr/bin/env python3
"""Re-skins the course lesson pages with the calm shared palette (assets/tokens.css).
Neon / harsh colours are mapped to theme tokens by role, so the pages work in glass / paper / sepia / kindle.
Safe to re-run: pages that already link tokens.css are skipped.
usage: python3 tools/reskin.py [--dry] [files...]    (run from the site root)"""
import colorsys, glob, io, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP = {  # generated by tools/menus.py
    'courses/menu.html', 'courses/HTML & CSS/menu.html', 'courses/HTML & CSS/html-menu.html', 'courses/Js/menu.html',
    'courses/php-course/index.html', 'courses/Python/menu.html', 'courses/React/menu.html', 'courses/Tailwind CSS/menu.html'}
DRY = '--dry' in sys.argv

FAMS = [(345, 360, 'red'), (0, 15, 'red'), (15, 45, 'orange'), (45, 70, 'yellow'), (70, 165, 'green'),
        (165, 200, 'cyan'), (200, 250, 'blue'), (250, 300, 'purple'), (300, 345, 'pink')]
STATIC = {'red': '#e68f8f', 'orange': '#dba078', 'yellow': '#e0c27a', 'green': '#9fcf95', 'cyan': '#7cc4d8',
          'blue': '#85b4ee', 'purple': '#b8a6e8', 'pink': '#dc9bbd'}
STATIC_ACCENT = '#6fc3a3'
FAMILY_NAMES = list(STATIC)

# tokens redefined inside code panels, so the panel stays dark + readable in every theme
SCOPE = (
    '--px-text:#cdd6e2;--px-text-strong:#eef2f7;--px-muted:#8b99ab;--px-faint:#6c7b8e;'
    '--px-line:rgba(190,205,225,.10);--px-line-strong:rgba(190,205,225,.22);--px-ink-rgb:190,205,225;'
    '--px-accent:#6fc3a3;--px-accent-rgb:111,195,163;--px-card:#1e2731;--px-card2:#242f3b;'
    '--text:#cdd6e2;--muted:#8b99ab;--border:rgba(190,205,225,.10);--border2:rgba(111,195,163,.22);--card:#1e2731;--card2:#262f3a;--surface:#181d24;--bg2:#181d24;--px-shade-rgb:0,0,0;--px-shade-k:1;'
    + ''.join('--px-c-%s:%s;--px-c-%s-rgb:%s;' % (n, STATIC[n], n, ','.join(str(int(STATIC[n][i:i + 2], 16)) for i in (1, 3, 5))) for n in FAMILY_NAMES)
)

HEX = re.compile(r'#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})\b')
RGBA = re.compile(r'rgba?\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})\s*(?:,\s*([\d.]+%?)\s*)?\)')
VAR_ROLE = {
    'bg': 'bg', 'void': 'bg', 'bg2': 'surface', 'bg3': 'card', 'surface': 'surface', 'sidebar-bg': 'surface',
    'header-dark': 'surface', 'card': 'card', 'card-bg': 'card', 'card2': 'card2',
    'editor': 'code', 'editor-bg': 'code', 'code-bg': 'code', 'code': 'code',
    'text': 'text', 'text-silver': 'text', 'muted': 'muted',
}


def parse_hex(h):
    h = h.lstrip('#')
    if len(h) in (3, 4):
        h = ''.join(c * 2 for c in h)
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def classify(r, g, b):
    hh, ll, ss = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    hue = hh * 360
    avg = (r + g + b) / 3
    if max(r, g, b) - min(r, g, b) < 22 or ss < 0.14 or (ll < 0.2 and ss < 0.5):
        # neutral (or very dark navy)
        if avg < 78:
            return ('dark', avg)
        if avg < 150:
            return ('mid', avg)
        return ('light', avg)
    if ll < 0.14:
        return ('dark', avg)
    if ss > 0.8 and 0.42 < ll < 0.7 and 92 <= hue <= 165:
        return ('neon', 0)
    if ss > 0.8 and 0.42 < ll < 0.7 and 165 < hue <= 200 and g > 190 and b > 190:  # electric cyan -> plain cyan family
        return ('fam', 'cyan')
    for lo, hi, name in FAMS:
        if lo <= hue < hi:
            return ('fam', name)
    return ('fam', 'red')


def dark_token(avg):
    if avg <= 12:
        return 'bg'
    if avg <= 23:
        return 'surface'
    if avg <= 34:
        return 'card'
    return 'card2'


def map_color(r, g, b, alpha, prop, ctx):
    """returns replacement string (var()/rgba(var()) or None to keep). prop: css property name or var role."""
    kind, info = classify(r, g, b)
    a = alpha
    p = (prop or '').lower()
    is_text = p == 'color' or p.endswith('-color') and 'background' not in p and 'border' not in p and 'outline' not in p
    if p in ('fill', 'stroke', 'stop-color', 'caret-color', 'text-decoration-color', 'accent-color'):
        is_text = True
    if kind == 'neon':
        return 'var(--px-accent)' if a is None else 'rgba(var(--px-accent-rgb),%s)' % a
    if kind == 'fam':
        n = info
        return 'var(--px-c-%s)' % n if a is None else 'rgba(var(--px-c-%s-rgb),%s)' % (n, a)
    if kind == 'dark':
        if is_text:
            return 'var(--px-on-accent)' if a is None else None
        if a is not None:
            return 'rgba(var(--px-bg-rgb),%s)' % a
        if ctx.get('code') and p.startswith('background'):
            ctx['used_code'] = True
            return 'var(--px-code-bg)'
        return 'var(--px-%s)' % dark_token(info)
    if kind == 'mid':
        if is_text:
            return 'var(--px-muted)' if info < 118 else 'var(--px-text)' if a is None else None
        if p.startswith('background'):
            return 'var(--px-card2)' if a is None else 'rgba(var(--px-ink-rgb),%s)' % a
        if p.startswith('border') or p.startswith('outline') or p == 'box-shadow':
            return 'var(--px-line-strong)' if a is None else 'rgba(var(--px-ink-rgb),%s)' % a
        return 'var(--px-muted)' if a is None else 'rgba(var(--px-ink-rgb),%s)' % a
    # light neutral
    if a is not None:
        if is_text:
            try:
                af = float(a[:-1]) / 100 if str(a).endswith('%') else float(a)
            except ValueError:
                af = 0
            # translucent white text (.4 / .5 / .85 …) must stay readable on light themes too
            if af >= .7:
                return 'var(--px-text)'
            if af >= .3 or (af >= .12 and not ctx.get('_var')):
                return 'var(--px-muted)'
        return 'rgba(var(--px-ink-rgb),%s)' % a
    if is_text:
        return 'var(--px-text-strong)' if info >= 225 else 'var(--px-text)'
    if p.startswith('background'):
        return 'var(--px-paper)' if info >= 225 else 'var(--px-text)'
    if p.startswith('border') or p.startswith('outline'):
        return 'var(--px-line-strong)'
    return 'var(--px-text)'


def recolor(value, prop, ctx):
    """replace every colour token inside a css value"""
    def rg(m):
        r, g, b = int(m.group(1)), int(m.group(2)), int(m.group(3))
        a = m.group(4)
        if (r, g, b) == (0, 0, 0):
            # black overlays: keep for shadows; on backgrounds use a theme-aware shade so light themes stay light
            if (prop or '').lower().startswith('background') and not ctx.get('code') and a is not None:
                return 'rgba(var(--px-shade-rgb),calc(%s*var(--px-shade-k)))' % a
            return m.group(0)
        rep = map_color(r, g, b, a, prop, ctx)
        return rep if rep else m.group(0)

    def hx(m):
        raw = m.group(1)
        r, g, b = parse_hex(raw)
        a = None
        if len(raw) in (4, 8):
            av = int(raw[-2:] if len(raw) == 8 else raw[-1] * 2, 16) / 255
            a = ('%.2f' % av).rstrip('0').rstrip('.')
        if (r, g, b) == (0, 0, 0) and a is None and (prop or '').lower() in ('color',):
            return 'var(--px-on-accent)'
        if (r, g, b) == (0, 0, 0) and (prop or '').startswith('background'):
            ctx['pure_black'] = True
            return 'var(--px-code-bg)' if ctx.get('code') else 'var(--px-bg)'
        rep = map_color(r, g, b, a, prop, ctx)
        return rep if rep else m.group(0)
    def named(m):
        w, pl = m.group(1).lower(), (prop or '').lower()
        if pl == 'color':
            return 'var(--px-text-strong)' if w == 'white' else 'var(--px-on-accent)'
        if pl.startswith('background'):
            if w == 'white':
                return 'var(--px-paper)'
            return 'var(--px-code-bg)' if ctx.get('code') else 'var(--px-bg)'
        return m.group(0)
    value = RGBA.sub(rg, value)
    value = HEX.sub(hx, value)
    value = NAMED.sub(named, value)
    return value


NAMED = re.compile(r'(?<![\w#-])(white|black)(?![\w-])', re.I)
DECL = re.compile(r'([\w-]+)\s*:\s*([^;{}]+)')


def recolor_decls(body, ctx, var_context=False):
    def d(m):
        prop, val = m.group(1), m.group(2)
        if not (HEX.search(val) or RGBA.search(val) or NAMED.search(val)):
            return m.group(0)
        if prop.startswith('--'):
            role = VAR_ROLE.get(prop[2:])
            single = HEX.fullmatch(val.strip())
            if single and role:
                kind, info = classify(*parse_hex(val.strip()))
                if role in ('bg', 'surface', 'card', 'card2', 'code', 'text', 'muted') and not (kind == 'neon'):
                    return '%s:var(--px-%s)' % (prop, {'code': 'code-bg'}.get(role, role))
            if prop[2:] in ('border',):
                return '%s:var(--px-line)' % prop
            if prop[2:] in ('border2', 'border-neon', 'bn'):
                return '%s:rgba(var(--px-accent-rgb),.22)' % prop
            ctx['_var'] = True
            try:
                return '%s:%s' % (prop, recolor(val, 'color', ctx))
            finally:
                ctx['_var'] = False
        return '%s:%s' % (prop, recolor(val, prop, ctx))
    return DECL.sub(d, body)


RULE = re.compile(r'([^{}@][^{}]*)\{([^{}]*)\}')
CODE_SEL = re.compile(r'code|editor|\bpre\b|textarea|terminal|console|output|preview|snippet|syntax|\.ln\b|line-|window|\.cm\b|\.term', re.I)
CODE_VAR_BG = re.compile(r'background(?:-color)?\s*:\s*var\(--(?:editor|editor-bg|code-bg|code|code-block)\)')


CUR = {'root': ''}
FILL_BG = re.compile(r'background(?:-color|-image)?\s*:\s*(?:var\(--(?:px-(?:c-[a-z]+|accent2?)|accent2?|tw2?)\)|linear-gradient\([^;]*?var\(--(?:px-(?:c-[a-z]+|accent2?)|accent2?|tw2?)\))', re.I)
TEXT_ON = re.compile(r'(?<![\w-])color\s*:\s*(?:#fff(?:fff)?|var\(--px-text-strong\)|var\(--px-text\)|var\(--px-on-accent\))(?=\s*(?:;|$))', re.I)
LIGHT_BG = re.compile(r'background(?:-color)?\s*:\s*var\(--px-paper\)')
HAS_COLOR = re.compile(r'(?<![\w-])color\s*:')
PAPER_FAM = {'red': '#b24545', 'orange': '#a85a22', 'yellow': '#8a6410', 'green': '#2f6b3a', 'cyan': '#1f6e82',
             'blue': '#2d5fa6', 'purple': '#5d4a9c', 'pink': '#a8456e'}
LIGHT_SCOPE = (
    '--px-text:#2a303c;--px-text-strong:#161b25;--px-muted:#5d6879;--px-faint:#8a94a4;'
    '--px-line:rgba(40,50,70,.10);--px-line-strong:rgba(40,50,70,.20);--px-ink-rgb:40,50,70;--px-accent:#15735e;--px-accent-rgb:21,115,94;'
    + ''.join('--px-c-%s:%s;--px-c-%s-rgb:%s;' % (n, v, n, ','.join(str(int(v[i:i + 2], 16)) for i in (1, 3, 5))) for n, v in PAPER_FAM.items())
)
WRAPPER_SEL = re.compile(r'^\.(code-block|code-window|terminal|console)$')


def collect_root(text):
    decls = []
    for sm in re.finditer(r'<style[^>]*>(.*?)</style>', text, re.S | re.I):
        for rm in re.finditer(r':root\s*\{([^{}]*)\}', sm.group(1)):
            new = recolor_decls(rm.group(1), {'code': False})
            for d in re.findall(r'--[\w-]+\s*:[^;]+', new):
                if 'var(--px-' in d and not d.strip().startswith(('--px-',)):
                    decls.append(d.strip())
    return (';' + ';'.join(decls)) if decls else ''


def css_transform(css):
    def rule(m):
        sel, body = m.group(1), m.group(2)
        sel = re.sub(r'/\*.*?\*/', '', sel, flags=re.S)
        ctx = {'code': bool(CODE_SEL.search(sel))}
        # a rule is a "code panel" only when it paints a dark background itself
        new = recolor_decls(body, ctx)
        if FILL_BG.search(new):
            new = TEXT_ON.sub('color:var(--px-on-fill)', new)
        used_code = ctx.get('used_code') or (ctx['code'] and CODE_VAR_BG.search(new))
        if CODE_VAR_BG.search(new) and not ctx['code']:
            used_code = True
        if used_code and 'background' in new:
            new = new.rstrip().rstrip(';') + ';' + SCOPE + CUR['root']
        elif LIGHT_BG.search(new) and not used_code:
            # a light "paper" card inside a dark theme: its own text must be dark and its colour families deep
            new = new.rstrip().rstrip(';') + ';' + LIGHT_SCOPE + ('' if HAS_COLOR.search(new) else 'color:var(--px-text);')
        elif WRAPPER_SEL.match(sel.strip()) and 'background' not in new:
            # a bare code wrapper is a dark panel too (its header / output boxes assume it)
            new = new.rstrip().rstrip(';') + ';background:var(--px-code-bg);' + SCOPE + CUR['root']
        return '%s{%s}' % (sel, new)
    return RULE.sub(rule, css)


def inline_style_transform(htmlpart):
    def tag(m):
        t = m.group(0)
        def st(sm):
            ctx = {'code': False}
            out = recolor_decls(sm.group(2), ctx)
            if FILL_BG.search(out):
                out = TEXT_ON.sub('color:var(--px-on-fill)', out)
            return sm.group(1) + out + sm.group(3)
        return re.sub(r'(\sstyle=")([^"]*)(")', st, t)
    return re.sub(r'<[a-zA-Z][^<>]*>', tag, htmlpart)


def script_transform(js):
    js = re.sub(r'#39ff14\b', STATIC_ACCENT, js, flags=re.I)
    js = re.sub(r'rgba\(\s*57\s*,\s*255\s*,\s*20\s*,', 'rgba(111,195,163,', js)
    return js


# softer static colours for the few places that must stay literal (shown source code, playgrounds)
SEGMENT = re.compile(r'(<textarea\b.*?</textarea>|<script\b.*?</script>|<style\b.*?</style>)', re.S | re.I)
GFONT = re.compile(r'<link[^>]+fonts\.googleapis\.com/css2[^>]*>', re.I)
FONT_LINK = '<link href="https://fonts.googleapis.com/css2?family=Cairo:wght@400;600;700;800;900&family=JetBrains+Mono:wght@400;500;700&family=Fira+Code:wght@400;500&family=Inter:wght@400;500;600;700&display=swap" rel="stylesheet">'


def depth_of(rel):
    return rel.count('/')  # 'courses/Js/x.html' -> 2


def reskin(rel, text):
    if 'assets/tokens.css' in text:
        return None
    CUR['root'] = collect_root(text)
    parts = SEGMENT.split(text)
    out = []
    for p in parts:
        low = p[:9].lower()
        if low.startswith('<style'):
            m = re.match(r'(<style[^>]*>)(.*)(</style>)', p, re.S | re.I)
            out.append(m.group(1) + css_transform(m.group(2)) + m.group(3))
        elif low.startswith('<script'):
            m = re.match(r'(<script[^>]*>)(.*)(</script>)', p, re.S | re.I)
            if m and 'src=' not in m.group(1):
                out.append(m.group(1) + script_transform(m.group(2)) + m.group(3))
            else:
                out.append(p)
        elif low.startswith('<textarea'):
            out.append(p)
        else:
            out.append(inline_style_transform(p))
    t = ''.join(out)
    # fonts: calm stack, no display fonts
    t = re.sub(r"'(Syne|Orbitron)'", "'Cairo'", t)
    t = re.sub(r'"(Syne|Orbitron)"', '"Cairo"', t)
    t = GFONT.sub('', t)
    rel_assets = '../' * (depth_of(rel))
    head_add = ('<meta name="theme-color" content="#14181e">\n' if 'name="theme-color"' not in t else '') + \
        FONT_LINK + '\n<link rel="stylesheet" href="%sassets/tokens.css">\n' % rel_assets
    # tokens + fonts first (so page :root can reference them), page styles, then lesson.css + site.js at the end of head
    if re.search(r'<head[^>]*>', t, re.I):
        t = re.sub(r'(<head[^>]*>)', lambda m: m.group(1) + '\n' + head_add, t, count=1, flags=re.I)
        tail = '<link rel="stylesheet" href="%sassets/lesson.css">\n<script src="%sassets/site.js"></script>\n' % (rel_assets, rel_assets)
        t = re.sub(r'</head>', lambda m: tail + '</head>', t, count=1, flags=re.I)
    t = re.sub(r'<html([^>]*)>', lambda m: '<html%s%s>' % (m.group(1), '' if 'data-theme' in m.group(1) else ' data-theme="dusk"'), t, count=1, flags=re.I)
    t = re.sub(r'<body([^>]*)>', lambda m: '<body%s%s>' % (m.group(1), '' if 'data-px-tools' in m.group(1) else ' data-px-tools'), t, count=1, flags=re.I)
    return t


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    files = args or sorted(glob.glob(os.path.join(ROOT, 'courses', '**', '*.html'), recursive=True))
    n = 0
    for f in files:
        rel = os.path.relpath(f, ROOT).replace(os.sep, '/')
        if rel in SKIP:
            continue
        s = io.open(f, encoding='utf8', errors='replace').read()
        t = reskin(rel, s)
        if t is None or t == s:
            continue
        n += 1
        if not DRY:
            io.open(f, 'w', encoding='utf8', newline='\n').write(t)
    print('re-skinned', n, 'files')


main()
